function createPlace(input) {
  const travelKnowledge = getTravelKnowledgeForPlace(input);
  const costBand = budgetBand(input.budget_level);
  const tags = unique([
    input.category.toLowerCase(),
    ...input.mood,
    ...input.ideal_for,
    ...(travelKnowledge.best_for || []),
    ...(travelKnowledge.climate_tags || []),
    ...input.retrieval_terms,
    costBand,
    crowdBand(input.crowd_level),
    input.family_friendly ? "family-friendly" : "adult-oriented"
  ]);

  return {
    ...input,
    country: input.country || "India",
    destination: input.city,
    avg_temp_monthly: input.avg_temp_monthly || travelKnowledge.avg_temp_monthly,
    peak_season: input.peak_season || travelKnowledge.peak_season,
    monsoon_months: input.monsoon_months || travelKnowledge.monsoon_months,
    climate_tags: input.climate_tags || travelKnowledge.climate_tags,
    seasonal_notes: input.seasonal_notes || travelKnowledge.seasonal_notes,
    best_for: unique([...(input.best_for || []), ...input.ideal_for, ...(travelKnowledge.best_for || [])]),
    type: input.category.toLowerCase().replace(/\s+/g, "_"),
    role: input.role || inferRole(input),
    cluster: input.cluster || input.city,
    tags,
    bestFor: input.ideal_for,
    dayWindows: input.day_windows || [],
    retrievalTerms: input.retrieval_terms,
    fatigue: Number((input.walking_required / 5).toFixed(2)),
    estimatedCost: input.cost_estimate_inr,
    durationMinutes: Math.round(input.visit_duration_hours * 60),
    popularity: Math.round((input.crowd_level / 5) * 100),
    travelTimeFromCenterMinutes: input.travel_time_from_center_minutes ?? 30,
    indoorOutdoor: input.indoor_outdoor || "outdoor",
    costBand,
    openingWindows: input.day_windows || [],
    groupFit: input.ideal_for,
    clusterPriority: clusterPriority(input),
    weatherFit: input.weather_fit ?? inferWeatherFit(input),
    sourceVisibility: "public-demo",
    semantic_summary: buildSemanticSummary(input)
  };
}

function buildSemanticSummary(place) {
  const travelKnowledge = getTravelKnowledgeForPlace(place);
  return [
    `${place.name} is a ${place.category.toLowerCase()} in ${place.city}, ${place.country || "India"}.`,
    `Mood: ${place.mood.join(", ")}.`,
    `Ideal for: ${place.ideal_for.join(", ")}.`,
    `Budget level ${place.budget_level}/5; crowd level ${place.crowd_level}/5; walking required ${place.walking_required}/5.`,
    `Best months: ${place.best_months.join(", ")}.`,
    `Peak season: ${(place.peak_season || travelKnowledge.peak_season || []).join(", ")}.`,
    `Monsoon months: ${(place.monsoon_months || travelKnowledge.monsoon_months || []).join(", ")}.`,
    `Climate tags: ${(place.climate_tags || travelKnowledge.climate_tags || []).join(", ")}.`,
    `Nightlife ${place.nightlife_score}/5, adventure ${place.adventure_score}/5, culture ${place.cultural_score}/5.`,
    place.summary
  ].join(" ");
}

function inferRole(place) {
  if (place.nightlife_score >= 4) return "social";
  if (place.adventure_score >= 4) return "adventure";
  if (place.cultural_score >= 4) return "anchor";
  if (place.crowd_level <= 2 || place.mood.includes("slow") || place.mood.includes("restorative")) return "recovery";
  if (place.day_windows?.includes("sunset")) return "visual";
  return "exploration";
}

function budgetBand(level) {
  if (level <= 1) return "low";
  if (level === 2) return "medium";
  if (level === 3) return "upper-medium";
  return "premium";
}

function crowdBand(level) {
  if (level <= 1) return "very-low-crowd";
  if (level === 2) return "low-crowd";
  if (level === 3) return "moderate-crowd";
  return "high-crowd";
}

function clusterPriority(place) {
  let priority = 58 + place.cultural_score * 4 + place.adventure_score * 3 + place.nightlife_score * 2;
  if (place.mood.includes("hidden")) priority += 8;
  if (place.family_friendly) priority += 4;
  return Math.min(priority, 96);
}

function inferWeatherFit(place) {
  if (["Heritage", "Temple", "Market"].includes(place.category)) return 72;
  if (["Beach", "Island", "Backwater", "Lake"].includes(place.category)) return 76;
  if (place.walking_required >= 4) return 58;
  return 68;
}

function unique(values) {
  return [...new Set(values.filter(Boolean).map((value) => String(value).trim().toLowerCase()))];
}
